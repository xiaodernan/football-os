class TestVisionMeasurement:
    def test_the_centroid_of_the_non_pitch_pixels_is_where_the_square_is(self) -> None:
        stats = frame_stats(ppm_frame(box=(6, 24, 8, 8)))
        assert stats.bright_centroid is not None
        assert stats.bright_centroid[0] == pytest.approx((6 + 3.5) / 96, abs=0.01)
        assert stats.bright_centroid[1] == pytest.approx((24 + 3.5) / 54, abs=0.01)
        assert stats.green_fraction > 0.98
        assert stats.bright_fraction == pytest.approx(64 / (96 * 54), abs=0.001)

    def test_a_shift_is_measured_in_frame_widths_not_in_pixels(self) -> None:
        left = frame_stats(ppm_frame(box=(6, 24, 8, 8)))
        right = frame_stats(ppm_frame(box=(30, 24, 8, 8)))
        motion = motion_between(left, right)
        assert motion["centroid_shift"] == pytest.approx(0.25, abs=0.01)
        assert motion["is_movement"] is True
        assert motion_between(left, left)["centroid_shift"] == 0.0
        assert motion_between(left, left)["is_movement"] is False

    def test_events_carry_a_time_a_position_and_the_sentence_that_justifies_them(self) -> None:
        provider = DemoVisionProvider(frame_times=[0.0, 0.5, 1.0])
        result = provider.analyze_frames([ppm_frame(box=(6, 24, 8, 8)), ppm_frame(box=(30, 24, 8, 8)), ppm_frame(box=(60, 24, 8, 8))])
        assert [event["t_s"] for event in result["events"]] == [0.5, 1.0]
        assert [round(event["x"], 2) for event in result["events"]] == [0.35, 0.66]
        assert all("non-pitch pixels moved" in event["why"] for event in result["events"])
        assert result["demo_mode"] is True
        assert result["provider"] == "demo-pixel-stats"
        assert "does not detect players" in result["limitations"]

    def test_a_still_frame_produces_no_events_and_says_so_by_being_empty(self) -> None:
        frame = ppm_frame(box=(40, 20, 8, 8))
        result = DemoVisionProvider(frame_times=[0.0, 0.5, 1.0]).analyze_frames([frame, frame, frame])
        assert result["events"] == []
        assert len(result["samples"]) == 3

    def test_no_frames_is_reported_as_the_absence_of_a_clip_not_as_a_clean_result(self) -> None:
        result = DemoVisionProvider().analyze_frames([])
        assert result["frames_seen"] == 0 and result["events"] == []
        assert "nothing to measure" in result["error"]

