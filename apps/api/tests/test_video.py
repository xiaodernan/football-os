API = "/api/v1/video"
HAS_FFMPEG = shutil.which("ffmpeg") is not None and shutil.which("ffprobe") is not None


def _clip_count(owner_id: str) -> int:
    with SessionLocal() as session:
        return int(session.scalar(select(func.count()).select_from(VideoAsset).where(VideoAsset.owner_id == owner_id)) or 0)


def ppm_frame(size: tuple[int, int] = (96, 54), box: tuple[int, int, int, int] | None = None) -> bytes:
    """A green field with an optional white square, as the raw PPM the pipeline reads."""
    width, height = size
    pixels = bytearray()
    for y in range(height):
        for x in range(width):
            inside = box is not None and box[0] <= x < box[0] + box[2] and box[1] <= y < box[1] + box[3]
            pixels.extend((255, 255, 255) if inside else (30, 125, 50))
    return f"P6\n{width} {height}\n255\n".encode() + bytes(pixels)


def build_clip(target: Path, *, moving: bool) -> None:
    source = "testsrc2=s=320x180:d=2:r=25" if moving else "color=c=0x1e7d32:s=320x180:d=2:r=25,drawbox=x=140:y=70:w=24:h=24:color=white:t=fill"
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", source, "-pix_fmt", "yuv420p", str(target)],
        check=True,
    )


@pytest.fixture(scope="module")
def clips(tmp_path_factory) -> dict[str, Path]:  # type: ignore[no-untyped-def]
    if not HAS_FFMPEG:
        pytest.skip("ffmpeg/ffprobe are not installed on this host")
    directory = tmp_path_factory.mktemp("clips")
    moving = directory / "moving.mp4"
    still = directory / "still.mp4"
    build_clip(moving, moving=True)
    build_clip(still, moving=False)
    return {"moving": moving, "still": still}


@pytest.fixture()
def store() -> SessionLocal:
    session = SessionLocal()
    try:
        yield session
    finally:
        session.close()


def upload(client, path: Path, *, title: str = "Session clip") -> object:
    with path.open("rb") as handle:
        return client.post(
            f"{API}/upload?title={title}",
            files={"file": (path.name, handle.read(), "video/mp4")},
        )


class TestVisionMeasurement:
    def test_the_centroid_of_the_non_pitch_pixels_is_where_the_square_is(self) -> None:
        stats = frame_stats(ppm_frame(box=(6, 24, 8, 8)))
        assert stats.bright_centroid is not None
        assert stats.bright_centroid[0] == pytest.approx((6 + 3.5) / 96, abs=0.01)
        assert stats.bright_centroid[1] == pytest.approx((24 + 3.5) / 54, abs=0.01)
        assert stats.green_fraction > 0.98
        assert stats.bright_fraction == pytest.approx(64 / (96 * 54), abs=0.001)

    def test_a_shift_is_measured_in_frame_widths_not_in_pixels(self) -> None:
        left = frame_stats(ppm_frame(box=(6, 24, 8, 8)))
        right = frame_stats(ppm_frame(box=(30, 24, 8, 8)))
        motion = motion_between(left, right)
        assert motion["centroid_shift"] == pytest.approx(0.25, abs=0.01)
        assert motion["is_movement"] is True
        assert motion_between(left, left)["centroid_shift"] == 0.0
        assert motion_between(left, left)["is_movement"] is False

    def test_events_carry_a_time_a_position_and_the_sentence_that_justifies_them(self) -> None:
        provider = DemoVisionProvider(frame_times=[0.0, 0.5, 1.0])
        result = provider.analyze_frames([ppm_frame(box=(6, 24, 8, 8)), ppm_frame(box=(30, 24, 8, 8)), ppm_frame(box=(60, 24, 8, 8))])
        assert [event["t_s"] for event in result["events"]] == [0.5, 1.0]
        assert [round(event["x"], 2) for event in result["events"]] == [0.35, 0.66]
        assert all("non-pitch pixels moved" in event["why"] for event in result["events"])
        assert result["demo_mode"] is True
        assert result["provider"] == "demo-pixel-stats"
        assert "does not detect players" in result["limitations"]

    def test_a_still_frame_produces_no_events_and_says_so_by_being_empty(self) -> None:
        frame = ppm_frame(box=(40, 20, 8, 8))
        result = DemoVisionProvider(frame_times=[0.0, 0.5, 1.0]).analyze_frames([frame, frame, frame])
        assert result["events"] == []
        assert len(result["samples"]) == 3

    def test_no_frames_is_reported_as_the_absence_of_a_clip_not_as_a_clean_result(self) -> None:
        result = DemoVisionProvider().analyze_frames([])
        assert result["frames_seen"] == 0 and result["events"] == []
        assert "nothing to measure" in result["error"]

    @pytest.mark.parametrize("blob", [b"not a ppm at all", b"P6\n96\n", b"P3\n96 54\n255\n", b"P6\n96 54\n255\nshort"])
    def test_a_malformed_or_unsupported_pixmap_is_refused(self, blob: bytes) -> None:
        with pytest.raises(ValueError):
            read_ppm(blob)


@pytest.mark.skipif(not HAS_FFMPEG, reason="ffmpeg/ffprobe not installed")
class TestMediaTools:
    def test_probe_reports_the_container_facts_the_pipeline_runs_on(self, clips) -> None:  # type: ignore[no-untyped-def]
        info = probe(clips["moving"])
        assert info.duration_s == pytest.approx(2.0, abs=0.1)
        assert (info.width, info.height) == (320, 180)
        assert info.fps > 20 and info.codec
        assert info.bitrate_kbps > 0
        assert info.aspect == pytest.approx(320 / 180, abs=0.01)

    def test_sampling_produces_distinct_frames_at_even_times(self, clips) -> None:  # type: ignore[no-untyped-def]
        interval = frame_interval(2.0, target_frames=8)
        frames = extract_frames(clips["moving"], clips["moving"].parent / "out", interval_s=interval)
        assert [frame.time_s for frame in frames[:3]] == [0.0, round(interval, 3), round(interval * 2, 3)]
        assert len({frame.path.read_bytes() for frame in frames}) == len(frames), "a moving clip must not sample the same frame twice"

    def test_a_display_copy_is_written_as_png_once(self, clips, tmp_path) -> None:  # type: ignore[no-untyped-def]
        frames = extract_frames(clips["moving"], tmp_path, interval_s=0.5)
        png = to_png(frames[0].path)
        assert png.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
        assert to_png(frames[0].path) == png

    def test_sampling_a_file_that_is_not_a_video_fails_loudly(self, tmp_path) -> None:
        not_a_video = tmp_path / "notes.mp4"
        not_a_video.write_bytes(b"definitely not a container")
        with pytest.raises(ValueError, match="ffmpeg failed"):
            extract_frames(not_a_video, tmp_path / "x", interval_s=0.5)


class TestUploadContract:
    def test_the_bytes_decide_and_a_renamed_file_is_refused(self, clips) -> None:  # type: ignore[no-untyped-def]
        assert detect_container(clips["moving"].read_bytes()) == "video/mp4"
        for name, blob in [("exe", b"MZ\x90\x00" + bytes(64)), ("jpeg", b"\xff\xd8\xff\xe0" + bytes(64)), ("text", b"hello world, not a video")]:
            with pytest.raises(UploadRejection, match="supported"):
                detect_container(blob[:16] if name == "exe" else blob)

    def test_an_empty_upload_is_refused_before_anything_is_stored(self, clips) -> None:  # type: ignore[no-untyped-def]
        with pytest.raises(UploadRejection, match="empty"):
            store_upload(SessionLocal(), user_id="usr_x", filename="empty.mp4", data=b"")

    def test_the_size_ceiling_is_enforced_before_the_disk_is_touched(self, clips) -> None:  # type: ignore[no-untyped-def]
        # `Settings` is frozen on purpose, so the ceiling is a parameter of the seam rather than
        # something a test pokes into a shared object.
        with pytest.raises(UploadTooLarge, match="exceeds"):
            store_upload(SessionLocal(), user_id="usr_x", filename="big.mp4", data=clips["moving"].read_bytes(), max_bytes=8)

    def test_a_key_cannot_climb_out_of_the_storage_root(self, tmp_path) -> None:
        from app.providers import LocalStorageProvider

        provider = LocalStorageProvider(str(tmp_path))
        provider.put("video/u/a.mp4", b"payload", "video/mp4")
        assert provider.get("video/u/a.mp4") == b"payload"
        with pytest.raises(ValueError, match="escapes"):
            provider.put("../../escaped.mp4", b"nope", "video/mp4")
        assert provider.url_for("video/u/a.mp4").startswith("/api/v1/video/file/")


@pytest.mark.skipif(not HAS_FFMPEG, reason="ffmpeg/ffprobe not installed")
class TestPipelineAndOwnership:
    def test_a_moving_clip_yields_detections_that_name_their_provider(self, auth_client, clips) -> None:  # type: ignore[no-untyped-def]
        response = upload(auth_client, clips["moving"])
        assert response.status_code == 201, response.text
        report = response.json()
        assert report["asset"]["status"] == "uploaded"
        assert report["asset"]["duration_s"] > 1.5
        assert report["detections"] == [], "uploading must not analyse on its own"

        analysed = auth_client.post(f"{API}/{report['asset']['id']}/analyse?target_frames=16")
        assert analysed.status_code == 200, analysed.text
        result = analysed.json()
        assert [stage["name"] for stage in result["stages"]] == ["probe", "extract_frames", "analyse"]
        sampled = result["analysis"]["frames_seen"]
        assert 4 <= sampled <= 16, sampled
        assert result["job"]["status"] == "DONE"
        assert result["job"]["result"]["frames"] == sampled == result["asset"]["frame_count"]
        assert result["stages"][1]["detail"]["sample_times"] == [round(index * result["asset"]["frame_interval_s"], 3) for index in range(min(8, sampled))]
        assert result["analysis"]["demo_mode"] is True
        assert result["detections"], "a moving test pattern contains motion; measuring none would be a silent failure"
        assert {row["provider"] for row in result["detections"]} == {"demo-pixel-stats"}
        assert all("does not detect" not in row["why"] for row in result["detections"])
        assert "not players, not a ball" in result["disclaimer"]

        with SessionLocal() as session:
            assert session.scalar(select(func.count()).select_from(VideoDetection).where(VideoDetection.asset_id == report["asset"]["id"])) == len(result["detections"])
            calls = list(session.scalars(select(ModelCall).where(ModelCall.feature == "video.analyse")).all())
            assert calls and calls[-1].demo_mode is True and calls[-1].success is True
            jobs = list(session.scalars(select(Job).where(Job.type == "video.analyse")).all())
            assert jobs and jobs[-1].payload["asset_id"] == report["asset"]["id"]

    def test_a_still_clip_produces_no_detections_and_still_reports_what_it_saw(self, auth_client, clips) -> None:  # type: ignore[no-untyped-def]
        report = upload(auth_client, clips["still"], title="Still").json()
        result = auth_client.post(f"{API}/{report['asset']['id']}/analyse").json()
        assert result["detections"] == [], "a static field has no movement to find"
        assert result["analysis"]["frames_seen"] > 1
        assert result["job"]["status"] == "DONE"
        assert result["analysis"]["green_fraction_mean"] > 0.9, "the generated clip really is mostly pitch-green"

    def test_frames_and_file_are_served_to_the_owner_as_png_and_mp4(self, auth_client, clips) -> None:  # type: ignore[no-untyped-def]
        report = upload(auth_client, clips["moving"]).json()
        asset_id = report["asset"]["id"]
        auth_client.post(f"{API}/{asset_id}/analyse")
        frame = auth_client.get(f"{API}/{asset_id}/frames/0")
        assert frame.status_code == 200 and frame.content[:4] == b"\x89PNG"
        assert frame.headers["content-type"] == "image/png"
        missing = auth_client.get(f"{API}/{asset_id}/frames/9999")
        assert missing.status_code == 404 and missing.json()["detail"]["code"] == "no_such_frame"
        clip = auth_client.get(f"{API}/{asset_id}/file")
        assert clip.status_code == 200 and clip.content == clips["moving"].read_bytes()

    def test_nothing_about_a_clip_is_readable_without_the_owners_session(self, auth_client, clips) -> None:  # type: ignore[no-untyped-def]
        asset_id = upload(auth_client, clips["moving"]).json()["asset"]["id"]
        from fastapi.testclient import TestClient

        from app.main import app

        # A separate client, not the `client` fixture: `auth_client` is built on that same instance
        # and carries its Authorization header, which is what made an earlier version of this test
        # "prove" anonymity while still signed in.
        with TestClient(app) as anonymous:
            assert anonymous.get(f"{API}/{asset_id}").status_code == 401
            assert anonymous.get(API).status_code == 401
            assert anonymous.get(f"{API}/{asset_id}/file").status_code == 401
            assert anonymous.get(API).status_code == 401

        from fastapi.testclient import TestClient

        from app.main import app

        with TestClient(app) as stranger:
            registered = stranger.post(
                "/api/v1/auth/register",
                json={"email": "video-stranger@example.test", "password": "strong-pass-1234", "display_name": "Stranger", "role": "coach", "accepts_data_policy": True},
            )
            stranger.headers.update({"Authorization": f"Bearer {registered.json()['access_token']}"})
            assert stranger.get(f"{API}/{asset_id}").status_code == 404
            assert stranger.get(f"{API}/{asset_id}/file").status_code == 404
            assert stranger.get(f"{API}/{asset_id}/frames/0").status_code == 404
            assert stranger.post(f"{API}/{asset_id}/analyse").status_code == 404
            assert stranger.get(f"{API}/{asset_id}/jobs").status_code == 404
            assert stranger.get(API).json()["items"] == []

    def test_deleting_removes_the_row_and_the_bytes(self, auth_client, clips) -> None:  # type: ignore[no-untyped-def]
        report = upload(auth_client, clips["moving"]).json()
        asset_id = report["asset"]["id"]
        report = auth_client.get(f"{API}/{asset_id}").json()
        assert "storage_key" not in report["asset"], "the internal path is not part of the contract"
        with SessionLocal() as session:
            asset = session.get(VideoAsset, asset_id)
            assert asset is not None
            path = Path(settings.storage_dir) / asset.storage_key
        assert path.is_file()
        assert auth_client.delete(f"{API}/{asset_id}").status_code == 204
        assert not path.exists(), "the record is worthless if the clip is still on the disk"
        with SessionLocal() as session:
            assert session.get(VideoAsset, asset_id) is None
            assert session.scalar(select(func.count()).select_from(VideoDetection).where(VideoDetection.asset_id == asset_id)) == 0

    def test_a_refused_container_never_reaches_storage(self, auth_client, tmp_path) -> None:  # type: ignore[no-untyped-def]
        fake = tmp_path / "not-a-video.mp4"
        fake.write_bytes(b"\x7fELF" + bytes(200))
        owner = auth_client.get("/api/v1/auth/me").json()["id"]
        before = _clip_count(owner)
        response = upload(auth_client, fake)
        assert response.status_code == 415
        assert response.json()["detail"]["code"] == "unsupported_container"
        assert _clip_count(owner) == before, "a refused upload must not leave a row behind"

    def test_the_per_account_clip_ceiling_is_enforced(self, auth_client, clips, monkeypatch) -> None:  # type: ignore[no-untyped-def]
        monkeypatch.setattr("app.api.v1.video.MAX_CLIPS_PER_USER", 1)
        assert upload(auth_client, clips["moving"]).status_code == 201
        overflow = upload(auth_client, clips["still"])
        assert overflow.status_code == 409
        assert overflow.json()["detail"]["code"] == "video_limit"

    def test_the_health_endpoint_names_the_vision_and_storage_providers(self, client) -> None:  # type: ignore[no-untyped-def]
        providers = client.get("/api/v1/healthz").json()["providers"]
        assert providers["vision"] == "demo-pixel-stats"
        assert providers["storage"] == "local-fs"
        assert providers["demo_mode"] is True


