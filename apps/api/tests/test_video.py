        team2 = world["away"].id
        match_resp = auth_client.post("/api/v1/simulate", json={
            "home_team": team1,
            "away_team": team2,
            "minutes": 90,
        })
        assert match_resp.status_code == 201, match_resp.text
        match_id = match_resp.json()["id"]

