"""M5 Video Analysis: the container decides, the pixels are measured, and a still clip says nothing.

Two kinds of test live here on purpose. The measurement maths is checked against PPMs built by hand,
where the expected centroid is arithmetic the test can write down exactly; the media and pipeline
tests drive real ffmpeg over a clip generated by the test itself, because "the tool ran" cannot be
proved with a fixture that pretends to be a video. A clip that does not move must produce zero
detections, and that null result is as much a requirement as a positive one.
"""

