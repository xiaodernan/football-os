def ppm_frame(size: tuple[int, int] = (96, 54), box: tuple[int, int, int, int] | None = None) -> bytes:
    """A green field with an optional white square, as the raw PPM the pipeline reads."""
    width, height = size
    pixels = bytearray()
    for y in range(height):
        for x in range(width):
            inside = box is not None and box[0] <= x < box[0] + box[2] and box[1] <= y < box[1] + box[3]
            pixels.extend((255, 255, 255) if inside else (30, 125, 50))
    return f"P6\n{width} {height}\n255\n".encode() + bytes(pixels)


def build_clip(target: Path, *, moving: bool) -> None:
    source = "testsrc2=s=320x180:d=2:r=25" if moving else "color=c=0x1e7d32:s=320x180:d=2:r=25,drawbox=x=140:y=70:w=24:h=24:color=white:t=fill"
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", source, "-pix_fmt", "yuv420p", str(target)],
        check=True,
    )


