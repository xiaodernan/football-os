@pytest.mark.skipif(not HAS_FFMPEG, reason="ffmpeg/ffprobe not installed")
class TestMediaTools:
    def test_probe_reports_the_container_facts_the_pipeline_runs_on(self, clips) -> None:  # type: ignore[no-untyped-def]
        info = probe(clips["moving"])
        assert info.duration_s == pytest.approx(2.0, abs=0.1)
        assert (info.width, info.height) == (320, 180)
        assert info.fps > 20 and info.codec
