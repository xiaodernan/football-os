"""Regenerate the manual spec constant in `app.services.manual_spec`.

The manual is the one page a reader hands to a friend ("start here"), so the answer the
model produces behind `/manual/ask` quotes only what this file prints. Regenerate:
`python scripts/regen_manual_spec.py`. A corpus change means a byte-review here in the
diff, not a silent drift in the answers.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "apps" / "web" / "messages" / "en.json"
OUT = ROOT / "apps" / "api" / "app" / "services" / "manual_spec.py"

LINES: list[str] = []


def _section(heading: str, body: str) -> None:
    LINES.append(f"## {heading}\n{body}\n")


def main() -> None:
    if not SRC.is_file():
        print(f"REFUSE: {SRC} missing")
        sys.exit(2)
    data = json.loads(SRC.read_text(encoding="utf-8"))
    manual = data["manual"]

    _section("The five-step quickstart", "\n".join(f"{index}. **{manual[f'quick{i}t']}** — {manual[f'quick{i}d']}" for index, i in enumerate(range(1, 6), start=1)))

    tour_lines = []
    for i in range(1, 22):
        tour_lines.append(f"- **{manual[f'tour{i}t']}** — {manual[f'tour{i}d']}")
    _section("The doors tour", "\n".join(tour_lines))

    _section("The rules of this world", "\n".join(f"- **{manual[f'rule{i}']}**" for i in range(1, 7)))

    faq_pairs = []
    for i in range(1, 5):
        faq_pairs.append(f"Q: {manual[f'faq{i}q']}\nA: {manual[f'faq{i}a']}")
    _section("Frequently asked", "\n\n".join(faq_pairs))

    g_titles = ("gSeedTitle", "gTierTitle", "gOverallTitle", "gXgTitle", "gFormTitle", "gStreakTitle", "gUpsetTitle", "gOriginTitle")
    g_bodies = tuple(t.replace("Title", "Body") for t in g_titles)
    glossary = "\n".join(f"- **{manual[t]}** — {manual[b]}" for t, b in zip(g_titles, g_bodies, strict=True))
    _section("Glossary", glossary)

    _section("Where the doors meet the manual — closing note", manual["closingNote"])

    body = (
        '"""The manual spec consumed by the /manual/ask door.\n\n'
        "Generated by `scripts/regen_manual_spec.py` from `apps/web/messages/en.json` — the same\n"
        "English the manual page prints. Do not hand-edit; re-run the generator and review the\n"
        "byte diff like you would the corpus.\n"
        '"""\n\n'
        f"MANUAL_CONTEXT = {json.dumps(chr(10).join(LINES).strip() + chr(10), ensure_ascii=False)}\n\n"
        f"MANUAL_SPEC_BYTES = {len(chr(10).join(LINES).strip().encode('utf-8'))}\n"
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    size = len(body.encode("utf-8"))
    print(f"wrote {OUT} — {size} bytes, {len(LINES)} sections")


if __name__ == "__main__":
    main()
