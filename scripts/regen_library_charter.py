"""Regenerate the library charter constant in library_charter.py from the corpus.

The charter is the byte-stable index the knowledge door bakes into its house contract: every
document title and section heading the library holds, in deterministic path order. Re-run this
script whenever the corpus changes, then update LIBRARY_CHARTER_BYTES in tests/test_library_charter.py.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "data" / "knowledge"
OUT = ROOT / "apps" / "api" / "app" / "services" / "knowledge" / "library_charter.py"

HEADER = (
    "\n\nTHE LIBRARY THE PASSAGES COME FROM — every section heading this library holds, in path order. "
    "This is the naming rail: it says what exists, nothing else. No citation may attach to this list; "
    "citations attach to the numbered passages that travel with a question.\n\n"
)


def _heading_lines(path: Path) -> tuple[str | None, list[str]]:
    text = path.read_text(encoding="utf-8")
    front_matter = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    title = None
    if front_matter:
        title_match = re.search(r'^title:\s*"(.*)"\s*$', front_matter.group(1), re.M)
        if title_match:
            title = title_match.group(1)
    sections: list[str] = []
    for line in text.splitlines():
        match = re.match(r"^(#{2,3})\s*(.+?)\s*$", line)
        if not match:
            continue
        sections.append(match.group(2).strip())
    if title is None:
        title = path.stem
    return title, sections


def main() -> None:
    if not SOURCES.is_dir():
        print(f"REFUSE: {SOURCES} is not a directory")
        sys.exit(2)
    files = sorted(p for p in SOURCES.rglob("*.md") if p.name.lower() != "readme.md")
    lines: list[str] = []
    for path in files:
        title, sections = _heading_lines(path)
        if not title:
            continue
        lines.append(title)
        lines.extend(f"    - {section}" for section in sections)
    if len(lines) < 500:
        print(f"REFUSE: only {len(lines)} index lines — this looks like an empty corpus, not a charter")
        sys.exit(3)
    charter_text = HEADER + "\n".join(lines) + "\n"

    body = (
        '"""The library charter — the index of everything this knowledge corpus holds.\n\n'
        "Regenerated by `scripts/regen_library_charter.py`, not edited by hand; the byte count is pinned by\n"
        "`tests/test_library_charter.py` so a silent refactor or a stale re-bake reds loudly. The knowledge\n"
        "door bakes this index into the same static prefix the gateway already caches — the naming rail for\n"
        "what exists in the library, never evidence.\n"
        '"""\n\n'
        f"LIBRARY_CHARTER = {json.dumps(charter_text, ensure_ascii=False)}\n"
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} — {len(lines)} index lines from {len(files)} documents, {len(charter_text.encode('utf-8'))} bytes")


if __name__ == "__main__":
    main()
